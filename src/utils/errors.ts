export class AppError extends Error {
  public readonly statusCode: number;
  public readonly code: string;
  public readonly isOperational: boolean;

  constructor(message: string, statusCode = 500, code = 'INTERNAL_ERROR', isOperational = true) {
    super(message);
    this.statusCode = statusCode;
    this.code = code;
    this.isOperational = isOperational;
    Object.setPrototypeOf(this, new.target.prototype);
  }
}

export class ValidationError extends AppError {
  constructor(message: string) {
    super(message, 400, 'VALIDATION_ERROR');
  }
}

export class NotFoundError extends AppError {
  constructor(message: string) {
    super(message, 404, 'NOT_FOUND');
  }
}

export class UnauthorizedError extends AppError {
  constructor(message = 'Unauthorized') {
    super(message, 401, 'UNAUTHORIZED');
  }
}

export class ForbiddenError extends AppError {
  constructor(message = 'Forbidden') {
    super(message, 403, 'FORBIDDEN');
  }
}

export class TenantIsolationError extends AppError {
  constructor(message = 'Access to another store data is strictly forbidden') {
    super(message, 403, 'TENANT_ISOLATION_VIOLATION');
  }
}

export class BudgetExceededError extends AppError {
  constructor(message = 'Monthly AI budget limit reached ($14.00 hard stop). Chat temporarily disabled.') {
    super(message, 429, 'AI_BUDGET_EXCEEDED');
  }
}
